/* Writes features/demo/catalog.feature: a journey over the Catalog sub-demo (src/pages/catalog.ts), one
   scenario per visual u2 tag in registry order — every sample the page renders claimed in its state, then
   the tag's typing or toggling gesture on its default sample. Tags, states and nouns come from
   libraries/u2/manifest.json, the claims from src/pages/catalog-states.json, the u2 defects a claim meets
   from catalog-known.json ({"<tag>": {"<step text>": "<owner: reason>"}}).
   With --check it compares instead of writing and exits 1 on drift. */
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const at = (path) => fileURLToPath(new URL(path, import.meta.url));
const read = (path) => JSON.parse(readFileSync(at(path), 'utf8'));

const manifest = read('../../../../libraries/u2/manifest.json');
const catalog = read('../../src/pages/catalog-states.json');
const known = existsSync(at('./catalog-known.json')) ? read('./catalog-known.json') : {};
const target = at('../features/demo/catalog.feature');

const problems = [];
const shown = manifest.components.filter((c) => c.visual !== false && !catalog.layoutOnly.includes(c.tag));
const nounOf = (c) => manifest.kinds.find((k) => k.kind === c.kind)?.noun;
const nounCount = new Map();
for (const c of shown)
  nounCount.set(nounOf(c), (nounCount.get(nounOf(c)) ?? 0) + 1);

/** The manifest's states of the tag in the page's order; the page renders a state by its own rule
 * (src/pages/catalog.ts), so the two must agree or a claim would name a sample that is not there. */
function statesOf(c) {
  const manifested = catalog.order.filter((s) => s === 'default' || s in (c.states ?? {}));
  const names = new Set(c.props.map((p) => p.name));
  const rendered = catalog.order.filter((s) => (catalog.requires[s] ?? []).every((p) => names.has(p)) &&
    !(catalog.unreached[s] ?? []).includes(c.tag));
  if (manifested.join() !== rendered.join())
    problems.push(`${c.tag}: the manifest lists [${manifested}], the Catalog page renders [${rendered}]`);
  for (const s of Object.keys(c.states ?? {}).filter((s) => !catalog.order.includes(s)))
    problems.push(`${c.tag}: state "${s}" has no place in catalog-states.json "order"`);
  return manifested;
}

/** The text the type gesture enters, in the form of the example's value; none for a value typing does not make. */
function typedText(c) {
  const type = c.props.find((p) => p.name === 'value')?.type;
  if (type === 'double' || type === 'int')
    return '42';
  return type !== 'string' ? undefined : /^#[0-9a-f]{6}$/i.test(c.example.props?.value ?? '') ? '#ff0000' : 'catalog';
}

const scenarios = shown.map((c) => {
  const noun = nounOf(c);
  if (noun === undefined)
    problems.push(`${c.tag}: no kind in the manifest names its noun`);
  const short = c.tag.replace(/^u2-/, '');
  const phrase = (state) => `"${short}-${state}" ${noun}`;
  const steps = [];
  for (const state of statesOf(c)) {
    if (catalog.claims[state] === undefined)
      problems.push(`${c.tag}: catalog-states.json has no claim for "${state}"`);
    steps.push(['Then', `${phrase(state)} should ${catalog.claims[state]}`]);
  }
  const gestures = manifest.kinds.find((k) => k.kind === c.kind)?.gestures ?? [];
  const text = gestures.includes('type') ? typedText(c) : undefined;
  if (text !== undefined) {
    steps.push(['When', `user types "${text}" into ${phrase('default')}`],
      ['Then', `${phrase('default')} should have value "${text}"`]);
  }
  if (gestures.includes('toggle') && c.props.find((p) => p.name === 'value')?.type === 'bool') {
    steps.push(['When', `user toggles ${phrase('default')}`],
      ['Then', `${phrase('default')} should be ${c.example.props?.value === true ? 'unchecked' : 'checked'}`]);
  }
  const title = nounCount.get(noun) > 1 ? `${noun} (${c.tag})` : noun;
  return {tag: c.tag, title, steps};
});

const lines = [
  '# generated by bdd/tools/gen-catalog.mjs from libraries/u2/manifest.json and src/pages/catalog-states.json',
  '# do not edit: `node bdd/tools/gen-catalog.mjs` regenerates, `--check` reports drift',
  '@demo @journey',
  'Feature: Component catalog',
  '  Every visual u2 component in each state its props can put it in, as the Catalog sub-demo renders it',
  '  from the registry: one scenario per tag, each sample found by its name (<tag>-<state>) and the noun',
  '  the u2 manifest gives its kind, then the tag\'s typing or toggling gesture on its default sample.',
];
for (const [tag, entries] of Object.entries(known)) {
  for (const [step, reason] of Object.entries(entries))
    lines.push(`  TODO: ${tag}: ${step} — ${reason}`);
}
lines.push('', '  Background:', '    Given user opens the "Catalog" demo page');

for (const s of scenarios) {
  const pinned = Object.keys(known[s.tag] ?? {});
  const pin = s.steps.findIndex(([, text]) => text === pinned[0]);
  if (pinned.length > 1)
    problems.push(`${s.tag}: catalog-known.json pins ${pinned.length} steps; a scenario pins one`);
  else if (pinned.length === 1 && pin < 0)
    problems.push(`${s.tag}: catalog-known.json pins "${pinned[0]}", which the scenario does not have`);
  lines.push('');
  // the tag line, then the Scenario line, then the steps: the pinned step is 2 + pin lines below the tag
  if (pin >= 0)
    lines.push(`  @known-failure:${lines.length + 1 + 2 + pin}`);
  lines.push(`  Scenario: ${s.title} in every state`);
  let previous;
  for (const [keyword, text] of s.steps) {
    lines.push(`    ${keyword === previous ? 'And' : keyword} ${text}`);
    previous = keyword;
  }
}
for (const tag of Object.keys(known).filter((t) => !scenarios.some((s) => s.tag === t)))
  problems.push(`${tag}: catalog-known.json names a tag the catalog does not show`);

if (problems.length > 0) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const feature = lines.join('\n') + '\n';
const summary = `${scenarios.length} scenarios, ${scenarios.reduce((n, s) => n + s.steps.length, 0)} steps`;
if (!process.argv.includes('--check')) {
  writeFileSync(target, feature);
  console.log(`${summary} → ${target}`);
}
else {
  /* the checked-in copy is CRLF in a Windows checkout, the generated string always LF */
  const actual = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (actual === feature)
    console.log(`catalog.feature is up to date (${summary})`);
  else {
    const a = actual.split('\n');
    const b = feature.split('\n');
    let i = 0;
    while (i < a.length && i < b.length && a[i] === b[i])
      i++;
    console.error(`catalog.feature is stale at line ${i + 1}:\n  has:  ${a[i] ?? '(end)'}\n` +
      `  want: ${b[i] ?? '(end)'}\nrun \`node bdd/tools/gen-catalog.mjs\` from packages/U2Demo`);
    process.exit(1);
  }
}
