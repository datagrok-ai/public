/// `grok kg gen`: kg.d.ts, the glossary.md tables and feature-tree.md, all inside the
/// knowledge-graph folder, from the type system and the home documents (conventions.md §11.2).
import * as fs from 'fs';
import * as path from 'path';
import {TypeSystem, NodeType, Member, Issue, pascal, graphLabel, firstSentence, nodeOrder, edgeOrder} from './types';
import {HomeSet, Home, Stub} from './homes';

export interface Output {
  /** Absolute path. */
  file: string;
  content: string;
}

export function generate(system: TypeSystem, kgRoot: string, repoRoot: string, homes: HomeSet | null): {outputs: Output[], errors: Issue[]} {
  const glossaryFile = path.join(kgRoot, 'glossary.md');
  const outputs: Output[] = [{file: path.join(kgRoot, 'kg.d.ts'), content: generateDts(system)}];
  const errors: Issue[] = [];
  if (fs.existsSync(glossaryFile)) {
    const missing = missingGlossaryHeading(fs.readFileSync(glossaryFile, 'utf8'));
    if (missing) errors.push({file: glossaryFile, code: 'glossary', message: `heading '${missing}' not found; the generated tables are spliced between the ${GLOSSARY_SECTIONS.join(', ')} headings`});
    else outputs.push({file: glossaryFile, content: spliceGlossary(fs.readFileSync(glossaryFile, 'utf8'), system, homes)});
  }
  if (homes) {
    const treeDir = path.relative(repoRoot, kgRoot).replace(/\\/g, '/');
    outputs.push({file: path.join(kgRoot, 'feature-tree.md'), content: generateFeatures(system, homes, treeDir)});
  }
  return {outputs, errors};
}

/** Writes the outputs, or with [check] only reports the ones that differ from disk. */
export function writeOutputs(outputs: Output[], check: boolean): {written: string[], stale: string[]} {
  const written: string[] = [];
  const stale: string[] = [];
  for (const out of outputs) {
    const current = fs.existsSync(out.file) ? fs.readFileSync(out.file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current === out.content) continue;
    if (check) stale.push(out.file);
    else {
      fs.writeFileSync(out.file, out.content, 'utf8');
      written.push(out.file);
    }
  }
  return {written, stale};
}

// ---------------------------------------------------------------- kg.d.ts

export function generateDts(system: TypeSystem): string {
  const lines: string[] = [
    '// Generated by `grok kg gen` from core/docs/knowledge-graph/{nodes,edges}/*.yaml. Do not edit.',
    '',
    'type Text = string;',
    'type Version = string;',
    'type Path = string;',
    'type Url = string;',
    'type Ref<T> = string;',
    `type Provenance = ${union(system.provenance)};`,
    '',
  ];
  for (const node of nodeOrder(system)) {
    const parent = node.extends ? ` extends ${pascal(node.extends)}` : '';
    lines.push(`/** ${firstSentence(node.description)} */`);
    lines.push(`export interface ${pascal(node.name)}${parent} {`);
    for (const m of Object.values(node.own)) lines.push(`  ${memberLine(m)}`);
    if (node.name === 'node')
      for (const m of system.buildFields.node) lines.push(`  ${memberLine(m)}`);
    lines.push('}', '');
  }
  const concreteEdges = edgeOrder(system).filter((e) => !e.abstract);
  for (const edge of concreteEdges) {
    lines.push(`/** ${firstSentence(edge.description)} */`);
    lines.push(`export interface ${pascal(edge.name)}Edge {`);
    lines.push(`  from: ${refType(edge.from)};`);
    lines.push(`  to: ${refType(edge.to)};`);
    for (const m of system.buildFields.edge) lines.push(`  ${memberLine(m)}`);
    for (const m of Object.values(edge.properties)) lines.push(`  ${memberLine(m)}`);
    lines.push('}', '');
  }
  const predicates = new Set<string>();
  for (const node of system.nodes.values())
    for (const m of Object.values(node.own))
      if (m.kind === 'ref') predicates.add(m.name);
  lines.push(`export type NodeTypeName = ${union([...system.nodes.keys()].sort())};`);
  lines.push(`export type EdgeTypeName = ${union(concreteEdges.map((e) => e.name).sort())};`);
  lines.push(`/** Reference properties: each materializes as a REF edge whose predicate is the property name (conventions.md §7.6). */`);
  lines.push(`export type RefPredicate = ${union([...predicates].sort())};`);
  lines.push(`/** The folder under edges/ each edge type is written in; a selector for querying, never part of a name (conventions.md §4). */`);
  lines.push('export interface EdgeGroups {');
  for (const edge of concreteEdges) lines.push(`  ${literal(edge.name)}: ${literal(edge.group)};`);
  lines.push('}', '');
  return lines.join('\n');
}

function literal(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function union(literals: string[]): string {
  return literals.length ? literals.map(literal).join(' | ') : 'never';
}

function memberLine(m: Member): string {
  return `${m.name}${m.nullable ? '?' : ''}: ${tsType(m)};`;
}

function tsType(m: Member): string {
  const base = baseType(m);
  if (!m.list) return base;
  return m.kind === 'enum' && m.literals!.length > 1 ? `(${base})[]` : `${base}[]`;
}

function baseType(m: Member): string {
  switch (m.kind) {
    case 'enum': return union(m.literals!);
    case 'ref': return refType(m.refs!);
    case 'record': return `Record<string, ${m.recordValue}>`;
  }
  switch (m.scalar) {
    case 'Date': case 'TypeUnion': case 'Member': return 'string';
    default: return m.scalar!;
  }
}

function refType(types: string[]): string {
  return `Ref<${types.map(pascal).join(' | ')}>`;
}

// ---------------------------------------------------------------- glossary.md

const GLOSSARY_SECTIONS = ['## Prefixes', '## Node types', '## Edge types', '## Concepts'];

/** The first of the four headings that is missing or out of order, or null. */
export function missingGlossaryHeading(markdown: string): string | null {
  let from = 0;
  for (const heading of GLOSSARY_SECTIONS) {
    const at = markdown.indexOf(heading, from);
    if (at < 0) return heading;
    from = at;
  }
  return null;
}

/** Regenerates the four tables; the Concepts table needs the homes and is left alone without them. */
export function spliceGlossary(markdown: string, system: TypeSystem, homes: HomeSet | null = null): string {
  const tables = [prefixTable(system), nodeTable(system), edgeTable(system)];
  let md = markdown.replace(/\r\n/g, '\n');
  for (let i = 0; i < tables.length; i++)
    md = splice(md, GLOSSARY_SECTIONS[i], GLOSSARY_SECTIONS[i + 1], tables[i]);
  return homes ? spliceConcepts(md, conceptTable(homes)) : md;
}

function splice(md: string, start: string, end: string, body: string): string {
  const a = md.indexOf(start);
  const b = md.indexOf(end, a);
  return `${md.slice(0, a)}${start}\n\n${body}\n\n${md.slice(b)}`;
}

/** Replaces the table under `## Concepts` (or appends one), keeping the hand-written intro lines above it. */
function spliceConcepts(md: string, table: string): string {
  const start = md.indexOf('## Concepts');
  const lines = md.slice(start).split('\n');
  let first = lines.findIndex((l) => l.startsWith('|'));
  let end = lines.length;
  if (first < 0) first = lines.length;
  else for (end = first; end < lines.length && lines[end].startsWith('|'); end++);
  const intro = lines.slice(0, first).join('\n').trimEnd();
  const rest = lines.slice(end).join('\n').trim();
  return `${md.slice(0, start)}${intro}\n\n${table}\n${rest ? `\n${rest}\n` : ''}`;
}

function conceptTable(homes: HomeSet): string {
  const rows = ['| Concept | Name | Area | One line | Defined by |', '|---|---|---|---|---|'];
  const concepts = homes.homes.filter((h) => h.type.chain.includes('concept')).sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  for (const c of concepts) {
    const definedBy = (Array.isArray(c.data.defined_by) ? c.data.defined_by : [])
      .map((item) => String(item && typeof item === 'object' ? (item as Record<string, unknown>).to ?? '' : item))
      .map((id) => id.includes('#') ? id.slice(id.lastIndexOf('#') + 1) : id);
    const area = c.data.area === undefined || c.data.area === null ? '' : String(c.data.area);
    rows.push(`| \`${c.localId}\` | ${cell(c.name)} | ${cell(area)} | ${cell(firstSentence(String(c.data.description ?? '')))} | ${[...new Set(definedBy)].map((d) => `\`${cell(d)}\``).join(', ')} |`);
  }
  return rows.join('\n');
}

function cell(value: unknown): string {
  return String(value ?? '').split(/\s+/).join(' ').trim().replace(/\|/g, '\\|');
}

function prefixTable(system: TypeSystem): string {
  const rows = ['| Written as | Type | Hierarchical | Authored | Home |', '|---|---|---|---|---|'];
  const feature = system.nodes.get('feature');
  rows.push(`| \`~a/b/c\` | feature | yes | yes | ${cell(feature?.home)} |`);
  for (const [prefix, typeName] of system.prefixes) {
    const t = system.nodes.get(typeName)!;
    const example = t.hierarchical ? `\`~${prefix}:a/b\`` : `\`~${prefix}:name\``;
    rows.push(`| ${example} | ${t.name} | ${yesNo(t.hierarchical)} | ${yesNo(t.authored)} | ${cell(t.home) || 'extracted'} |`);
  }
  rows.push('| `GROK-12345`, `gh:public#4062`, `bb#964` | ticket, pull-request | no | no | tracker ids, as they are |');
  rows.push('| `pkg:Chem`, `func:Chem:detectMolecules`, `file:<path>` | component subtypes | no | no | extracted, never hand-written |');
  return rows.join('\n');
}

function yesNo(v: boolean): string {
  return v ? 'yes' : 'no';
}

function nodeTable(system: TypeSystem): string {
  const rows = ['| Type | Root | Extends | One line |', '|---|---|---|---|'];
  for (const t of nodeOrder(system)) {
    const root = t.name === 'node' ? '' : t.root ?? '';
    rows.push(`| ${t.name}${t.abstract ? ' *(abstract)*' : ''} | ${root} | ${t.extends ?? ''} | ${cell(firstSentence(t.description))} |`);
  }
  return rows.join('\n');
}

const EDGE_INTRO = 'An edge is named by its file, grouped by its folder, referred to by name; a group is a selector, never\n' +
  'part of a name. `edges/ref.yaml` is the mechanism behind reference properties (§7.6) and sits in no group.';

/** One table per `edges/` folder, the folders in schema order, the ungrouped ones under a last heading. */
function edgeTable(system: TypeSystem): string {
  const out: string[] = [EDGE_INTRO];
  let group: string | null = null;
  for (const e of edgeOrder(system)) {
    if (e.group !== group) {
      group = e.group;
      out.push('', `### ${group || 'reference'}`, '',
        '| Edge | Label | From → To | Extends | Key | Derived by | One line |', '|---|---|---|---|---|---|---|');
    }
    const key = e.key === undefined ? '' : `\`${e.key}:\`${e.keySide === 'to' ? ' (on target)' : ''}`;
    const ends = `${e.from.map(pascal).join(' \\| ')} → ${e.to.map(pascal).join(' \\| ')}`;
    out.push(`| \`${e.name}\`${e.abstract ? ' *(abstract)*' : ''} | ${graphLabel(e.name)} | ${ends} | ${e.extends ?? ''} | ${key} | ${e.derivedBy.join(', ')} | ${cell(firstSentence(e.description))} |`);
  }
  return out.join('\n');
}

// ---------------------------------------------------------------- feature-tree.md

interface TreeNode {
  id: string;
  home?: Home;
  stub?: Stub;
  children: Map<string, TreeNode>;
}

const FEATURES_HEADER = '<!-- Generated by `grok kg gen` from the home documents (conventions.md §5). Do not edit; add or move a `feature:` key instead. -->';

/** The tree as markdown; home links are relative to [treeDir], the folder the file is written to. */
export function generateFeatures(system: TypeSystem, homes: HomeSet, treeDir = 'core/docs/knowledge-graph'): string {
  const families = new Map<string, TreeNode>();
  // The tree a type belongs to is the outermost hierarchical ancestor sharing its prefix: feature, concept, initiative, scenario.
  const familyOf = (t: NodeType) => [...t.chain].reverse().find((n) => system.nodes.get(n)?.hierarchical && system.nodes.get(n)?.prefix === t.prefix) ?? t.name;
  const insert = (family: string, localId: string, prefix: string | undefined, set: (n: TreeNode) => void) => {
    let node = families.get(family);
    if (!node) families.set(family, node = {id: '', children: new Map()});
    const segments = localId.split('/');
    for (let i = 0; i < segments.length; i++) {
      const childId = (prefix ? `${prefix}:` : '') + segments.slice(0, i + 1).join('/');
      let child = node.children.get(segments[i]);
      if (!child) node.children.set(segments[i], child = {id: childId, children: new Map()});
      node = child;
    }
    set(node);
  };
  for (const home of homes.homes) {
    if (!home.type.hierarchical) continue;
    insert(familyOf(home.type), home.localId, home.prefix, (n) => n.home = home);
  }
  for (const stub of homes.stubs) {
    const localId = stub.id.replace(/^[A-Z][A-Za-z]{0,5}:/, '');
    const prefix = stub.id.includes(':') ? stub.id.split(':')[0] : undefined;
    insert(familyOf(stub.type), localId, prefix, (n) => n.stub = n.home ? undefined : stub);
  }
  const lines = [FEATURES_HEADER, '', '# Feature tree', ''];
  if (!families.size) {
    lines.push('No home documents yet: no markdown file under the discovery roots carries a `feature:` or prefixed `id:` key.', '');
    return lines.join('\n');
  }
  const order = [...families.keys()].sort((a, b) => familyRank(system, a) - familyRank(system, b) || (a < b ? -1 : 1));
  for (const family of order) {
    lines.push(`## ${plural(family)}`, '');
    renderChildren(families.get(family)!, 0, lines, treeDir);
    lines.push('');
  }
  return lines.join('\n');
}

function familyRank(system: TypeSystem, family: string): number {
  const t = system.nodes.get(family);
  return family === 'feature' ? -1 : Math.max(system.roots.indexOf(t?.root ?? ''), 0);
}

function plural(typeName: string): string {
  const words = typeName.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
  return words.endsWith('y') ? `${words.slice(0, -1)}ies` : `${words}s`;
}

function renderChildren(node: TreeNode, depth: number, lines: string[], treeDir: string): void {
  for (const key of [...node.children.keys()].sort()) {
    const child = node.children.get(key)!;
    const indent = '  '.repeat(depth);
    if (child.home) {
      const link = path.posix.relative(treeDir, child.home.file);
      lines.push(`${indent}- \`~${child.id}\` — ${child.home.name || key} ([home](${link}))`);
    } else
      lines.push(`${indent}- \`~${child.id}\` *(no home yet)*`);
    renderChildren(child, depth + 1, lines, treeDir);
  }
}
