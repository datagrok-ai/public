/* Writes bindings/common/u2-kinds.g.ts — the table bindings/common/kinds.ts registers the u2 nouns
   from (src/u2-vocabulary.ts) — from the `kinds` of the u2 and EMS manifests (CONTRACT §4).
   --manifest <path> (repeatable) reads other manifests, --out <path> writes elsewhere; an entry's own
   `source` (the test fixture's) wins over the manifest's folder name. With --check it compares
   instead of writing, so a vocabulary older than a manifest fails. */
import {readFileSync, writeFileSync} from 'node:fs';
import {basename, dirname, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const FIELDS = ['kind', 'noun', 'aliases', 'family', 'tag', 'role', 'focusRole', 'nameFrom', 'parts', 'state', 'props',
  'gestures', 'items', 'partOf', 'source'];
const REQUIRED = {kind: 'string', noun: 'string', family: 'string', nameFrom: 'array', parts: 'object', state: 'array',
  props: 'array', gestures: 'array'};

const here = dirname(fileURLToPath(import.meta.url));
const publicRoot = resolve(here, '../../..');

function fail(message, code = 1) {
  console.error(message);
  process.exit(code);
}

const argv = process.argv.slice(2);
const valueOf = (flag) => argv.flatMap((a, i) => a === flag && i + 1 < argv.length ? [argv[i + 1]] : []);
const manifests = valueOf('--manifest').map((p) => resolve(p));
if (manifests.length === 0)
  manifests.push(resolve(here, '../../u2/manifest.json'), resolve(here, '../../ems/manifest.json'));
const out = resolve(valueOf('--out')[0] ?? resolve(here, '../bindings/common/u2-kinds.g.ts'));
const posix = (p) => relative(publicRoot, p).split('\\').join('/');

const seen = new Map();
const specs = [];
for (const path of manifests) {
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(path, 'utf8'));
  }
  catch (e) {
    fail(`cannot read ${path}: ${e.message}`);
  }
  const source = basename(dirname(path)) === 'ems' ? 'ems' : 'u2';
  if (!Array.isArray(manifest.kinds))
    fail(`the ${source} manifest has no "kinds" yet (WO-C3): ${path}`, 2);
  if (manifest.kindsVersion !== 1)
    fail(`${path}: kindsVersion ${manifest.kindsVersion}, this generator reads 1`);
  for (const entry of manifest.kinds) {
    for (const [field, type] of Object.entries(REQUIRED)) {
      const ok = type === 'array' ? Array.isArray(entry[field]) : typeof entry[field] === type;
      if (!ok)
        fail(`${path}: kind ${JSON.stringify(entry.kind)} has no ${type} "${field}"`);
    }
    if (seen.has(entry.kind))
      fail(`kind "${entry.kind}" is in ${seen.get(entry.kind)} and ${path}`);
    seen.set(entry.kind, path);
    const spec = {...entry, source: entry.source ?? source};
    specs.push(Object.fromEntries(FIELDS.filter((f) => spec[f] !== undefined).map((f) => [f, spec[f]])));
  }
}
specs.sort((a, b) => a.kind < b.kind ? -1 : a.kind > b.kind ? 1 : 0);

const text = `/* generated by tool/gen-u2-kinds.mjs from ${manifests.map(posix).join(' and ')}
   (kindsVersion 1) — do not edit; \`npm run vocab\` regenerates, \`npm run vocab:check\` reports drift */
import type {U2KindSpec} from '../../src/u2-vocabulary.js';

export const U2_KINDS: U2KindSpec[] = ${JSON.stringify(specs, null, 2)};
`;
const count = (source) => specs.filter((s) => s.source === source).length;
const nouns = new Set(specs.filter((s) => s.partOf === undefined).map((s) => s.noun));
const summary = `${specs.length} kinds (${count('u2')} u2, ${count('ems')} ems; ${specs.length - specs.filter((s) => s.partOf === undefined).length} ` +
  `parts of other kinds), ${nouns.size} nouns`;

if (!argv.includes('--check')) {
  writeFileSync(out, text);
  console.log(`${summary} → ${out}`);
}
else {
  /* a Windows checkout has the file with CRLF, the generated string is always LF */
  const lf = (s) => s.replace(/\r\n/g, '\n');
  let actual = '';
  try {
    actual = lf(readFileSync(out, 'utf8'));
  }
  catch {
    // a missing file is as stale as an old one
  }
  if (actual === text)
    console.log(`${basename(out)} is up to date (${summary})`);
  else {
    const a = actual.split('\n');
    const b = text.split('\n');
    let i = 0;
    while (i < a.length && i < b.length && a[i] === b[i])
      i++;
    console.error(`${basename(out)} is stale — run \`npm run vocab\` and commit the result.`);
    console.error(`  first difference at line ${i + 1}:`);
    console.error(`    checked in: ${i < a.length ? a[i] : '<end of file>'}`);
    console.error(`    generated:  ${i < b.length ? b[i] : '<end of file>'}`);
    process.exit(1);
  }
}
