/* Builds src/styles.g.ts — every sheet css/all.css lists, inlined, comments dropped — stamped with
   the revision in css/styles.lock.json, which the page-wide install orders copies by (src/styles.ts).
   A build takes the committed revision as it is: a working copy a few edits ahead must not outrank
   master's CSS on a shared stand. `--bump` mints the next revision for changed sheets — run it and
   commit the lock with the CSS; on CI (`CI` set) or with --check a stale lock fails. */
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const LOCK = join(root, 'css', 'styles.lock.json');
const OUT = join(root, 'src', 'styles.g.ts');

/** The sheet with its relative `@import`s inlined, depth first, each sheet once. */
function inline(file, seen = new Set()) {
  if (seen.has(file))
    return '';
  seen.add(file);
  return readFileSync(file, 'utf8').replace(/@import\s+['"](\.[^'"]+)['"]\s*;/g,
    (_, rel) => inline(join(dirname(file), rel), seen));
}

/** Drops comments outside strings, trims lines and drops the empty ones. */
function compact(css) {
  let out = '';
  let quote = null;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (quote) {
      out += c;
      if (c === '\\')
        out += css[++i] ?? '';
      else if (c === quote)
        quote = null;
    }
    else if (c === '"' || c === '\'') {
      quote = c;
      out += c;
    }
    else if (c === '/' && css[i + 1] === '*') {
      const end = css.indexOf('*/', i + 2);
      i = end < 0 ? css.length : end + 1;
    }
    else
      out += c;
  }
  return out.split(/\r?\n/).map((l) => l.trim()).filter((l) => l).join('\n');
}

const css = compact(inline(join(root, 'css', 'all.css')));
const hash = createHash('sha256').update(css).digest('hex').slice(0, 12);
const lock = existsSync(LOCK) ? JSON.parse(readFileSync(LOCK, 'utf8')) : {revision: 0, hash: ''};

if (lock.hash !== hash) {
  if (process.argv.includes('--check') || process.env.CI) {
    console.error(`u2: css/styles.lock.json is stale (hash ${lock.hash}, the sheets hash to ${hash}). ` +
      'Run `npm run styles -- --bump` in libraries/u2 and commit the lock with the CSS.');
    process.exit(1);
  }
  if (process.argv.includes('--bump')) {
    lock.revision += 1;
    lock.hash = hash;
    writeFileSync(LOCK, JSON.stringify(lock, null, 2) + '\n');
    console.log(`u2: stylesheet revision ${lock.revision} (${hash})`);
  }
  else
    console.warn(`u2: the stylesheets changed since revision ${lock.revision}; before committing, run ` +
      '`npm run styles -- --bump`');
}

writeFileSync(OUT, '// Generated by scripts/gen-styles.mjs from css/all.css — do not edit.\n' +
  `export const U2_STYLES = {revision: ${lock.revision}, hash: '${hash}', css: ${JSON.stringify(css)}};\n`);
