/* Writes src/components/display/icon-names.ts from the platform's Font Awesome Pro sheets:
   every `.fa-{name}:before` in fontawesome.css is an icon; the ones duotone.css also carries are
   the Pro set, the rest are brands (`fab` only). Pass the css directory as the first argument;
   the default is the core checkout next to this repo. Rerun on a Font Awesome bump. */
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const dir = process.argv[2] ?? fileURLToPath(new URL(
  '../../../../core/client/xamgle/web/font/font-awesome/css/', import.meta.url));
const names = (file, re) => {
  const set = new Set();
  for (const m of readFileSync(`${dir}/${file}`, 'utf8').matchAll(re))
    set.add(m[1]);
  return set;
};
const all = names('fontawesome.css', /\.fa-([a-z0-9-]+):before/g);
const pro = names('duotone.css', /\.fad\.fa-([a-z0-9-]+):after/g);
const version = /Font Awesome Pro ([\d.]+)/.exec(readFileSync(`${dir}/fontawesome.css`, 'utf8'))?.[1] ?? '?';

const sorted = [...all].sort();
const icons = sorted.filter((n) => pro.has(n));
const brands = sorted.filter((n) => !pro.has(n));

function block(list) {
  const lines = [];
  let line = ' ';
  for (const name of list) {
    if (line.length + name.length + 1 > 98) {
      lines.push(line);
      line = ' ';
    }
    line += ` ${name}`;
  }
  lines.push(line);
  return lines.join('\n');
}

const out = `/* Generated by scripts/gen-icon-names.mjs from Font Awesome Pro ${version} — do not edit. */

/** Every non-brand icon the platform's Font Awesome sheet carries (light / regular / solid). */
export const ICON_NAMES: readonly string[] = \`
${block(icons)}
\`.trim().split(/\\s+/);

/** The brand icons: one face (\`fab\`), which \`icon()\` picks for them on its own. */
export const BRAND_ICON_NAMES: readonly string[] = \`
${block(brands)}
\`.trim().split(/\\s+/);
`;

const path = fileURLToPath(new URL('../src/components/display/icon-names.ts', import.meta.url));
writeFileSync(path, out);
console.log(`${icons.length} icons + ${brands.length} brands (FA Pro ${version}) → ${path}`);
